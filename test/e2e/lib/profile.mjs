/**
 * Build one throwaway DSH profile for the real-process e2e harness.
 *
 * The profile is a normal custom profile (`$DSH_HOME/profiles/<name>`), not a
 * product mode: it composes the shipped `dsh-base` + `dsh-headless` bundles,
 * inserts two tiny fixture services the panel injects (`webServer`,
 * `connection`), the scripted LLM adapter, and finally the plugin under test
 * by absolute path — the working tree, never an installed copy.
 *
 * Everything the run needs lives under one temporary root:
 *
 *   <root>/home/profiles/e2e   the profile (DSH_HOME + DSH_PROFILE_DIR)
 *   <root>/work                the session working directory
 *   <root>/out                 the exported artefacts
 *   <root>/script.json         the scripted model program
 *   <root>/team-board.json     the fixture probe's last board snapshot
 */

import { copyFile, mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

/** Fixture files copied beside the generated patch file. */
const FIXTURE_PLUGINS = ['scripted-llm.js', 'web-server-stub.js', 'connection-stub.js', 'team-board-probe.js', 'tool-transcript.js', 'class-a-probe.js', 'seat-race-probe.js', 'crash-injector.js'];

export const PROFILE_NAME = 'e2e';

/** Bundle list for one profile variant: `team` also composes the real Agent Team. */
function bundles({ team }) {
  const list = ['@deepseek-ai/dsh-base', '@deepseek-ai/dsh-headless'];
  if (team) list.push('@deepseek-ai/dsh-experimental-agent-team-profile');
  return list;
}

/**
 * The profile's patch layer. Inserted paths are anchored beside this file, so
 * the fixture plugins travel with the profile and the panel is referenced by
 * absolute path.
 */
function patchLayer({ fixtureDir, pluginRoot, scriptPath, teamBoardPath, transcriptPath, team, crash }) {
  const rows = [
    `    - id: e2e-scripted-llm
      name: ./plugins/scripted-llm.js
      config:
        script: ${JSON.stringify(scriptPath)}`,
    `    - id: e2e-web-server
      name: ./plugins/web-server-stub.js`,
    `    - id: e2e-connection
      name: ./plugins/connection-stub.js`,
  ];
  rows.push(`    - id: e2e-tool-transcript
      name: ./plugins/tool-transcript.js
      config:
        out: ${JSON.stringify(transcriptPath)}`);
  // The concurrency probe dispatches two real tool calls at the same instant,
  // which a scripted, one-call-per-step model cannot do (ticket #9).
  rows.push(`    - id: e2e-seat-race-probe
      name: ./plugins/seat-race-probe.js`);
  if (team) {
    rows.push(`    - id: e2e-team-probe
      name: ./plugins/team-board-probe.js
      config:
        out: ${JSON.stringify(teamBoardPath)}`);
    // The team profile replaces `tool-subagent` and disables `ralph`; these
    // named stubs stand in for the class A tools the headless profile does not
    // ship, so a refusal can be proven down to the tool body.
    rows.push(`    - id: e2e-class-a-probe
      name: ./plugins/class-a-probe.js`);
  }
  // The crash injector must run its post-execute listener BEFORE the plugin
  // under test, so its SIGKILL lands between the Team board's commit and the
  // Reins ledger write. Fixture plugins are inserted ahead of the panel.
  if (crash !== undefined && crash !== false) {
    const tool = typeof crash.tool === 'string' ? crash.tool : 'team_task_update';
    const action = typeof crash.action === 'string' ? crash.action : undefined;
    rows.push(`    - id: e2e-crash-injector
      name: ./plugins/crash-injector.js
      config:
        tool: ${JSON.stringify(tool)}${action === undefined ? '' : `
        action: ${JSON.stringify(action)}`}`);
  }
  rows.push(`    - id: summary-panel
      name: ${JSON.stringify(pluginRoot)}
      config: {}`);
  return [
    '# Generated by test/e2e — throwaway profile, deleted after a passing run.',
    '- insert:',
    ...rows,
    '# The API gateway drives the real web app over a real HTTP server; a headless',
    '# run has neither, and its presence would wake the fixture webServer stub.',
    '- id: typert-gateway',
    "  name: '@deepseek-ai/dsh-api-gateway'",
    '  disabled: true',
    '# Route the agent at the scripted adapter instead of a credentialed provider.',
    '- id: agent-default-model',
    "  name: '@deepseek-ai/dsh-agent-default-model'",
    '  config:',
    '    provider: scripted',
    '    model: scripted-1',
    '',
  ].join('\n');
}

/**
 * Write the scripted model program a run consumes.
 *
 * A multi-run scenario rewrites it between runs: each `dsh` process reads
 * `script.json` once at boot, exactly like a real profile reads its config.
 * @param profile - the value `buildProfile` returned.
 * @param spec - `{ program, subagentProgram, teamResponses }`.
 */
export async function writeScript(profile, spec = {}) {
  await writeFile(profile.scriptPath, `${JSON.stringify({
    responses: Array.isArray(spec.program) ? spec.program : [],
    ...(Array.isArray(spec.subagentProgram) ? { subagentResponses: spec.subagentProgram } : {}),
    ...(spec.teamResponses !== null && typeof spec.teamResponses === 'object' ? { teamResponses: spec.teamResponses } : {}),
  }, null, 2)}\n`);
}

/**
 * Create the profile, its fixture plugins, and the run directories.
 * @param options - `{ root, pluginRoot, fixtureDir, program, subagentProgram,
 *   teamResponses, team, crash }`; `crash` adds the SIGKILL fixture.
 * @returns the paths the run and the collector need.
 */
export async function buildProfile({ root, pluginRoot, fixtureDir, program, subagentProgram, teamResponses, team = false, crash }) {
  const home = join(root, 'home');
  const profileDir = join(home, 'profiles', PROFILE_NAME);
  const pluginsDir = join(profileDir, 'plugins');
  const workdir = join(root, 'work');
  const outDir = join(root, 'out');
  const scriptPath = join(root, 'script.json');
  const teamBoardPath = join(root, 'team-board.json');
  const transcriptPath = join(root, 'tool-transcript.json');
  await Promise.all([mkdir(pluginsDir, { recursive: true }), mkdir(workdir, { recursive: true }), mkdir(outDir, { recursive: true })]);
  for (const file of FIXTURE_PLUGINS) {
    await copyFile(join(fixtureDir, file), join(pluginsDir, file));
  }
  const profile = {
    home, profileDir, workdir, outDir, scriptPath, teamBoardPath, transcriptPath,
    taskTreeDir: join(profileDir, 'agent-task-tree'),
  };
  await writeScript(profile, { program, subagentProgram, teamResponses });
  await writeFile(
    join(profileDir, 'package.json'),
    `${JSON.stringify({
      name: `dsh-profile-${PROFILE_NAME}`,
      private: true,
      type: 'module',
      dsh: { profile: { bundles: bundles({ team }), patchReload: 'startup' } },
    }, null, 2)}\n`,
  );
  await writeFile(join(profileDir, 'cordis.yml'), '[]\n');
  await writeFile(join(profileDir, 'cordis.patch.yml'), patchLayer({
    fixtureDir, pluginRoot, scriptPath, teamBoardPath, transcriptPath, team, crash,
  }));
  return profile;
}
